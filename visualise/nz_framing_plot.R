# -------------------
# LaTeX table: choice probabilities by framing arm and package type, and the
# tests of the net-zero information effect
# -------------------

pct  <- function(x) sprintf("%.1f", 100 * x)
# signed, with a real minus sign and no "-0.0" from rounding
spct <- function(x) {
  x <- round(100 * x, 1)
  x[x == 0] <- 0
  if_else(x == 0, "0.0", sub("^-", "$-$", sprintf("%+.1f", x)))
}
pval <- function(p) if_else(p < 0.001, "$<$0.001", sprintf("%.3f", p))

prob_rows <- nz_choice |>
  arrange(nz_binary, framing) |>
  transmute(row = sprintf("%s, %s & %s\\%% & [%s, %s] & & \\\\",
                          nz_binary, tolower(framing), pct(prob),
                          pct(asymp.LCL), pct(asymp.UCL)))

